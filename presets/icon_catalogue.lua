-- Add a category module here to expose another tab; picker and storage need no changes.
local catalogue = { categories = {
    (require("presets/icon_categories/skills")),
    (require("presets/icon_categories/weapons")),
    (require("presets/icon_categories/holidays")),
    (require("presets/icon_categories/misc")),
    (require("presets/icon_categories/bosses")),
} }
local byKey, categoryKeys = {}, {}
for _, category in ipairs(catalogue.categories) do
    assert(not categoryKeys[category.key], "Duplicate icon category: " .. category.key)
    categoryKeys[category.key] = true
    for _, entry in ipairs(category.entries) do
        assert(not byKey[entry.key], "Duplicate icon key: " .. entry.key)
        assert(entry.category == category.key, "Icon category mismatch: " .. entry.key)
        byKey[entry.key] = entry
    end
end

-- Metadata lookup is independent of the client API and resource availability.
-- An empty key means the native number; unknown keys have the same fallback.
function catalogue.get(key)
    if type(key) ~= "string" then return nil end
    if byKey[key] then return byKey[key] end
    -- Dynamic backpack selections remain usable after the item leaves the inventory.
    local digits = key:match("^item:([1-9]%d*)$")
    local objectID = digits and tonumber(digits)
    if not objectID or objectID > 2147483647 or tostring(objectID) ~= digits then return nil end
    return { key = key, category = "backpack", name = "Item " .. digits,
        objectID = objectID, width = 36, height = 32 }
end

-- Item names are display metadata, not part of the persisted icon identity.
-- Keep this lookup out of get/resolve, which are called on every draw.
function catalogue.objectName(object)
    local ok, name = pcall(function() return object and object.name end)
    if not ok or type(name) ~= "string" then return nil end
    name = name:gsub("[%c<>]", ""):match("^%s*(.-)%s*$")
    if name == "" then return nil end
    return name
end

function catalogue.displayName(key)
    local entry = catalogue.get(key)
    if not entry then return nil end
    if entry.category == "backpack" then
        local ok, object = pcall(function()
            return config and config.Obj and config.Obj.FromID(entry.objectID)
        end)
        if ok then return catalogue.objectName(object) or entry.name end
    end
    return entry.name
end

-- Resolve at use time, not module load: IDs may change between client versions.
-- nil means retain the number. Renderers must still handle sprite setup failure.
-- Optional sprites argument allows API-free tests and other catalogue consumers.
function catalogue.resolve(key, sprites)
    local entry = catalogue.get(key)
    if not entry then return nil end
    if entry.objectID then return entry.objectID, entry end
    sprites = sprites or (id and id.Sprite)
    if not sprites then return nil end
    local spriteID = sprites[entry.sprite]
    if type(spriteID) ~= "number" or spriteID < 0 or spriteID % 1 ~= 0 then return nil end
    return spriteID, entry
end

-- Item artwork is generated by the client, not part of id.Sprite.
function catalogue.apply(sprite, assetID, entry)
    if entry.objectID then
        -- Quantity is an optional Uint64, not a regular Lua number. Omit it
        -- for icon-only rendering to avoid native overload conversion errors.
        sprite:SetAssociatedObject(assetID)
        sprite.associatedObjectQuantityMode = ui.ObjectQuantityDisplayMode.NEVER
        assert(sprite.associatedObjectID == assetID, "Native item assignment was not accepted.")
    else
        if sprite.associatedObjectID and sprite.associatedObjectID >= 0 then
            sprite:SetAssociatedObject(-1)
        end
        sprite.sprite = assetID
        assert(sprite.spriteID == assetID, "Native sprite assignment was not accepted.")
    end
end

return catalogue
